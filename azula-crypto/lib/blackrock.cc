std::uint64_t BlackRock2::next_power_of_two(std::uint64_t num) noexcept
{
    if (num == 0)
    {
        return 1;
    }
    std::uint64_t power = 1;
    ++num;

    while ((1ULL << power) < num)
    {
        ++power;
    }
    return 1ULL << power;
}

std::uint64_t BlackRock2::bit_count(std::uint64_t num) noexcept
{
    std::uint64_t bits = 0;

    while ((num >> bits) > 1)
    {
        ++bits;
    }
    return bits;
}




BlackRock2 BlackRock2::create(std::uint64_t range,std::uint64_t seed,unsigned rounds)
{
    if (range == 0)
    {
        throw std::invalid_argument("BlackRock2: range must be > 0");
    }
    const std::uint64_t a = next_power_of_two(static_cast<std::uint64_t>(std::sqrt(static_cast<double>(range))));
    const std::uint64_t b = next_power_of_two(range / a);
    return BlackRock2{range, a, b, seed, rounds};
}

BlackRock2::BlackRock2(std::uint64_t range,std::uint64_t a,std::uint64_t b,std::uint64_t seed,unsigned rounds) noexcept
    : range_(range),a_(a),b_(b),a_bits_(bit_count(a)),a_mask_(a - 1ULL),b_bits_(bit_count(b)),b_mask_(b - 1ULL),seed_(seed),rounds_(rounds)
{

}


std::uint64_t BlackRock2::round(std::uint64_t r, std::uint64_t R) const noexcept
{
    const std::uint64_t T = R ^ ((seed_ >> r) | (seed_ << (64 - r)));
    std::uint64_t Y;

    if (r & 1)
    {
        Y = SB8[(T) & 0x3F] ^ SB6[(T >>  8) & 0x3F] ^ SB4[(T >> 16) & 0x3F] ^ SB2[(T >> 24) & 0x3F];
    }
    else
    {
        Y = SB7[(T) & 0x3F] ^ SB5[(T >>  8) & 0x3F] ^ SB3[(T >> 16) & 0x3F] ^ SB1[(T >> 24) & 0x3F];
    }
    return Y;
}


std::uint64_t BlackRock2::encrypt(std::uint64_t m) const noexcept
{
    std::uint64_t L = m & a_mask_;
    std::uint64_t R = m >> a_bits_;
    unsigned j = 1;

    for (; j <= rounds_; )
    {
        std::uint64_t tmp = (L + round(j, R)) & a_mask_;
        L = R;
        R = tmp;
        ++j;
        tmp = (L + round(j, R)) & b_mask_;
        L = R;
        R = tmp;
        ++j;
    }

    if ((j - 1) & 1)
    {
        return (L << a_bits_) + R;
    }
    else
    {
        return (R << a_bits_) + L;
    }
}

std::uint64_t BlackRock2::decrypt(std::uint64_t m) const noexcept
{
    std::uint64_t L, R;

    if (rounds_ & 1)
    {
        R = m % a_;
        L = m / a_;
    }
    else
    {
        L = m % a_;
        R = m / a_;
    }

    for (unsigned j = rounds_; j >= 1; --j)
    {
        std::uint64_t tmp = round(j, L);

        if (j & 1)
        {
            if (tmp > R)
            {
                tmp = tmp - R;
                tmp = a_ - (tmp % a_);

                if (tmp == a_)
                {
                    tmp = 0;
                }

            }
            else
            {
                tmp = (R - tmp) % a_;
            }
        }
        else
        {
            if (tmp > R)
            {
                tmp = tmp - R;
                tmp = b_ - (tmp % b_);

                if (tmp == b_)
                {
                    tmp = 0;
                }
            }
            else
            {
                tmp = (R - tmp) % b_;
            }
        }
        R = L;
        L = tmp;
    }
    return a_ * R + L;
}


std::uint64_t BlackRock2::shuffle(std::uint64_t index) const noexcept
{
    std::uint64_t c = encrypt(index);

    while (c >= range_)
    {
        c = encrypt(c);
    }
    return c;
}

std::uint64_t BlackRock2::unshuffle(std::uint64_t value) const noexcept
{
    std::uint64_t c = decrypt(value);

    while (c >= range_)
    {
        c = decrypt(c);
    }
    return c;
}


bool BlackRock2::selftest()
{
    {
        auto br = BlackRock2::create(1000, 0, 6);

        for (std::uint64_t i = 0; i < 10; ++i)
        {
            const auto shuffled = br.shuffle(i);
            const auto original = br.unshuffle(shuffled);

            if (i != original)
            {
                return false;
            }
        }
    }
    std::uint64_t range = 3015 * 3;

    for (int i = 0; i < 5; ++i)
    {
        range += 11 + i;
        range *= 1 + i;
        auto br = BlackRock2::create(range, static_cast<std::uint64_t>(std::time(nullptr)), 6);
        std::vector<std::uint8_t> seen(static_cast<std::size_t>(range), 0);

        for (std::uint64_t idx = 0; idx < range; ++idx)
        {
            const auto x = br.shuffle(idx);
            if (x >= range)
            {
                return false;
            }
            if (seen[static_cast<std::size_t>(x)] != 0)
            {
                return false;
            }
            seen[static_cast<std::size_t>(x)] = 1;
        }
        if (!std::all_of(seen.begin(), seen.end(), [](std::uint8_t v){ return v == 1; }))
        {
            return false;
        }
    }
    return true;
}











